-- =====================================================================
-- Pacotão - criação das tabelas e sequences (Oracle)
-- Ordem: primeiro as tabelas que não dependem de ninguém, depois as
-- que apontam para elas (por causa das chaves estrangeiras).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1) Tabelas sem dependência
-- ---------------------------------------------------------------------

CREATE TABLE TB_REGIAO (
    CD_REGIAO   NUMBER(10)    NOT NULL,
    NM_REGIAO   VARCHAR2(80)  NOT NULL,
    CONSTRAINT PK_REGIAO PRIMARY KEY (CD_REGIAO)
);

CREATE TABLE TB_CENTRO_DISTRIBUICAO (
    CD_CENTRO     NUMBER(10)    NOT NULL,
    NM_CENTRO     VARCHAR2(100) NOT NULL,
    DS_ENDERECO   VARCHAR2(200) NOT NULL,
    VL_LATITUDE   NUMBER(9,6)   NOT NULL,
    VL_LONGITUDE  NUMBER(9,6)   NOT NULL,
    CONSTRAINT PK_CENTRO PRIMARY KEY (CD_CENTRO)
);

-- DS_SENHA_HASH guarda o hash (BCrypt tem 60 caracteres), nunca a senha.
CREATE TABLE TB_ENTREGADOR (
    CD_ENTREGADOR  NUMBER(10)    NOT NULL,
    NM_ENTREGADOR  VARCHAR2(100) NOT NULL,
    DS_EMAIL       VARCHAR2(120) NOT NULL,
    DS_SENHA_HASH  VARCHAR2(100) NOT NULL,
    NR_TELEFONE    VARCHAR2(20)  NOT NULL,
    CONSTRAINT PK_ENTREGADOR PRIMARY KEY (CD_ENTREGADOR),
    CONSTRAINT UK_ENTREGADOR_EMAIL UNIQUE (DS_EMAIL)
);


-- ---------------------------------------------------------------------
-- 2) Tabelas que dependem das anteriores
-- ---------------------------------------------------------------------

-- Associativa do N:N entre entregador e região.
-- A chave primária é composta: o mesmo par não se repete.
CREATE TABLE TB_ENTREGADOR_REGIAO (
    CD_ENTREGADOR  NUMBER(10) NOT NULL,
    CD_REGIAO      NUMBER(10) NOT NULL,
    CONSTRAINT PK_ENTREGADOR_REGIAO PRIMARY KEY (CD_ENTREGADOR, CD_REGIAO),
    CONSTRAINT FK_ENTREG_REG_ENTREG FOREIGN KEY (CD_ENTREGADOR)
        REFERENCES TB_ENTREGADOR (CD_ENTREGADOR),
    CONSTRAINT FK_ENTREG_REG_REGIAO FOREIGN KEY (CD_REGIAO)
        REFERENCES TB_REGIAO (CD_REGIAO)
);

CREATE TABLE TB_CLIENTE (
    CD_CLIENTE     NUMBER(10)    NOT NULL,
    CD_REGIAO      NUMBER(10)    NOT NULL,
    NM_CLIENTE     VARCHAR2(100) NOT NULL,
    DS_EMAIL       VARCHAR2(120) NOT NULL,
    DS_SENHA_HASH  VARCHAR2(100) NOT NULL,
    NR_WHATSAPP    VARCHAR2(20)  NOT NULL,
    DS_ENDERECO    VARCHAR2(200) NOT NULL,
    VL_LATITUDE    NUMBER(9,6)   NOT NULL,
    VL_LONGITUDE   NUMBER(9,6)   NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (CD_CLIENTE),
    CONSTRAINT UK_CLIENTE_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT FK_CLIENTE_REGIAO FOREIGN KEY (CD_REGIAO)
        REFERENCES TB_REGIAO (CD_REGIAO)
);

-- O lote já nasce com o entregador dono dele (CD_ENTREGADOR NOT NULL).
-- DT_INICIO_ROTA e as coordenadas atuais ficam nulas até a rota começar.
CREATE TABLE TB_LOTE (
    CD_LOTE            NUMBER(10)   NOT NULL,
    CD_CENTRO          NUMBER(10)   NOT NULL,
    CD_ENTREGADOR      NUMBER(10)   NOT NULL,
    DS_CODIGO_QR       VARCHAR2(30) NOT NULL,
    DS_STATUS          VARCHAR2(20) DEFAULT 'MONTAGEM' NOT NULL,
    DT_CRIACAO         TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    DT_INICIO_ROTA     TIMESTAMP,
    VL_LATITUDE_ATUAL  NUMBER(9,6),
    VL_LONGITUDE_ATUAL NUMBER(9,6),
    CONSTRAINT PK_LOTE PRIMARY KEY (CD_LOTE),
    CONSTRAINT UK_LOTE_QR UNIQUE (DS_CODIGO_QR),
    CONSTRAINT FK_LOTE_CENTRO FOREIGN KEY (CD_CENTRO)
        REFERENCES TB_CENTRO_DISTRIBUICAO (CD_CENTRO),
    CONSTRAINT FK_LOTE_ENTREGADOR FOREIGN KEY (CD_ENTREGADOR)
        REFERENCES TB_ENTREGADOR (CD_ENTREGADOR),
    CONSTRAINT CK_LOTE_STATUS CHECK (DS_STATUS IN ('MONTAGEM', 'EM_ROTA', 'CONCLUIDO'))
);


-- ---------------------------------------------------------------------
-- 3) Encomenda e evento de rastreio
-- ---------------------------------------------------------------------

-- A encomenda já entra com lote (o Java escolhe o entregador e o lote
-- antes de gravar). NR_POSICAO_ROTA fica nulo até o QR ser lido.
CREATE TABLE TB_ENCOMENDA (
    CD_ENCOMENDA        NUMBER(10)   NOT NULL,
    CD_CENTRO           NUMBER(10)   NOT NULL,
    CD_LOTE             NUMBER(10)   NOT NULL,
    CD_CLIENTE          NUMBER(10)   NOT NULL,
    DS_CODIGO_RASTREIO  VARCHAR2(30) NOT NULL,
    NR_POSICAO_ROTA     NUMBER(3),
    DS_STATUS           VARCHAR2(20) DEFAULT 'NO_CD' NOT NULL,
    CONSTRAINT PK_ENCOMENDA PRIMARY KEY (CD_ENCOMENDA),
    CONSTRAINT UK_ENCOMENDA_RASTREIO UNIQUE (DS_CODIGO_RASTREIO),
    CONSTRAINT FK_ENCOMENDA_CENTRO FOREIGN KEY (CD_CENTRO)
        REFERENCES TB_CENTRO_DISTRIBUICAO (CD_CENTRO),
    CONSTRAINT FK_ENCOMENDA_LOTE FOREIGN KEY (CD_LOTE)
        REFERENCES TB_LOTE (CD_LOTE),
    CONSTRAINT FK_ENCOMENDA_CLIENTE FOREIGN KEY (CD_CLIENTE)
        REFERENCES TB_CLIENTE (CD_CLIENTE),
    CONSTRAINT CK_ENCOMENDA_STATUS CHECK (DS_STATUS IN ('NO_CD', 'EM_ROTA', 'ENTREGUE', 'FALHA')),
    CONSTRAINT CK_ENCOMENDA_POSICAO CHECK (NR_POSICAO_ROTA IS NULL OR NR_POSICAO_ROTA >= 1)
);

CREATE TABLE TB_EVENTO_RASTREIO (
    CD_EVENTO      NUMBER(10)   NOT NULL,
    CD_ENCOMENDA   NUMBER(10)   NOT NULL,
    DS_TIPO        VARCHAR2(20) NOT NULL,
    DT_EVENTO      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EVENTO PRIMARY KEY (CD_EVENTO),
    CONSTRAINT FK_EVENTO_ENCOMENDA FOREIGN KEY (CD_ENCOMENDA)
        REFERENCES TB_ENCOMENDA (CD_ENCOMENDA),
    CONSTRAINT CK_EVENTO_TIPO CHECK (DS_TIPO IN ('EM_ROTA', 'AVISO_ENVIADO', 'ENTREGUE', 'FALHA'))
);


-- ---------------------------------------------------------------------
-- 4) Sequences (uma por tabela com chave própria)
-- O INSERT do Java usa SQ_TB_X.NEXTVAL para gerar o código.
-- TB_ENTREGADOR_REGIAO não tem sequence: a chave é composta.
-- ---------------------------------------------------------------------

CREATE SEQUENCE SQ_TB_REGIAO              START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SQ_TB_CENTRO_DISTRIBUICAO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SQ_TB_ENTREGADOR          START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SQ_TB_CLIENTE             START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SQ_TB_LOTE                START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SQ_TB_ENCOMENDA           START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SQ_TB_EVENTO_RASTREIO     START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;


